def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def stamp():
    return datetime.now(timezone.utc).isoformat()


def tree(root):
    return {p.relative_to(root).as_posix(): sha(p) for p in sorted(root.rglob("*"))
            if p.is_file() and not any(x in {".git", ".terraform", "__pycache__"} for x in p.parts)
            and not re.search(r"\.tfstate|\.tfplan|\.class$|\.pyc$", p.name)}


def inside(root, relative):
    p = (root / relative).resolve()
    if not p.is_relative_to(root.resolve()):
        raise ValueError("Path escapes study materials")
    return p


def new_dir(path):
    path.mkdir(parents=True, exist_ok=False)


def verify_export(folder, model, pinned_generator=None):
    """Validate the observation receipt produced by the actual Java exporter."""
    receipt = read(folder / "receipt.json")
    if receipt.get("producer") != "MlopsDslStudyExportTest" or receipt["source_sha256"] != sha(model):
        raise ValueError("Unverified/stale Xtext export or model hash mismatch")
    if pinned_generator and receipt["generator_class_sha256"] != pinned_generator:
        raise ValueError("Generator differs from the frozen implementation")
    if receipt["artifacts"] != tree(folder / "artifacts"):
        raise ValueError("Xtext artifact manifest mismatch")
    if receipt["generator"] not in {"ACCEPT", "REJECT"}:
        raise ValueError("Blocked generator export")
    if (receipt["generator"] == "ACCEPT") != bool(receipt["artifacts"]):
        raise ValueError("Contradictory generation receipt")
    return receipt


def build_baseline(source, out, kubectl):
    import yaml
    new_dir(out)
    shutil.copytree(source, out / "artifacts")
    command = [kubectl, "kustomize", str(source.resolve())]
    try:
        p = subprocess.run(command, capture_output=True, text=True, encoding="utf-8", timeout=60)
        code, stdout, stderr = p.returncode, p.stdout, p.stderr
    except (OSError, subprocess.TimeoutExpired) as e:
        code, stdout, stderr = None, "", str(e)
    (out / "stdout.txt").write_text(stdout, encoding="utf-8")
    (out / "stderr.txt").write_text(stderr, encoding="utf-8")
    status = "BLOCKED" if code is None else "PASS" if code == 0 else "FAIL"
    if code == 0:
        kinds = {"Deployment": "deployment", "Service": "service", "Ingress": "ingress", "Namespace": "namespace"}
        docs = list(yaml.safe_load_all(stdout))
        if len(docs) != 4 or {d.get("kind") for d in docs} != set(kinds):
            raise ValueError("Unexpected baseline resource set")
        for d in docs:
            target = out / "artifacts/runtime/k8s" / (kinds[d["kind"]] + ".yaml")
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(yaml.safe_dump(d, sort_keys=False), encoding="utf-8")
    save(out / "receipt.json", {"command": command, "status": status, "exit_code": code,
                                "source": tree(source), "artifacts": tree(out / "artifacts")})
    return status


def inspect(provider, output, contract):
    if provider == "azure":
        from run_journal_comparison import inspect as checker
    else:
        from run_gcp_comparison import inspect as checker
    result = checker(output, contract)
    return {"parsing_errors": result["parsing_errors"], "domain_issues": result["domain_oracle"],
            "failed_requirements": [c["id"] for c in result["requirements"] if c["status"] != "PASS"],
            "requirements_checked": len(result["requirements"])}


def passes(observation):
    return not any(observation[k] for k in ("parsing_errors", "domain_issues", "failed_requirements"))


def unintended_changes(before, after, contract_before, contract_after):
    """Compare every YAML leaf in selected runtime/policy files, ignoring layout.

    Only paths whose expected value changes in the predeclared contract may
    change. This check is distinct from the existing positive requirements.
    """
    import yaml
    first = {c["id"]: c for c in contract_before["checks"]}
    allowed = {}
    for c in contract_after["checks"]:
        if c.get("kind") == "yaml" and c.get("expected") != first[c["id"]].get("expected"):
            allowed.setdefault(c["file"], []).append(c["path"])
    def leaves(value, path=()):
        if isinstance(value, dict) and value:
            return {p: v for k, child in value.items() for p, v in leaves(child, path + (k,)).items()}
        if isinstance(value, list) and value:
            return {p: v for k, child in enumerate(value) for p, v in leaves(child, path + (k,)).items()}
        return {path: value}
    def matches(pattern, path):
        return len(path) >= len(pattern) and all(a == "*" or a == b for a, b in zip(pattern, path))
    names = {p.relative_to(root).as_posix() for root in (before, after)
             for prefix in ("runtime/k8s", "mlops") for p in (root / prefix).glob("*.yaml")}
    unexpected = []
    missing = object()
    for name in sorted(names):
        a = leaves(yaml.safe_load((before / name).read_text())) if (before / name).exists() else {}
        b = leaves(yaml.safe_load((after / name).read_text())) if (after / name).exists() else {}
        for path in a.keys() | b.keys():
            if a.get(path, missing) != b.get(path, missing) and not any(matches(p, path) for p in allowed.get(name, [])):
                unexpected.append({"file": name, "path": list(path)})
    return unexpected


def block_values(records, metric):
    blocks = {}
    for row in records:
        blocks.setdefault(row["block_id"], {}).setdefault(row["participant_id"], {}).setdefault(row["approach"], []).append(row)
    values = []
    for bid, people in sorted(blocks.items()):
        if len(people) != 2:
            raise ValueError("Incomplete allocation block: " + bid)
        differences = []
        for pid, approaches in people.items():
            if set(approaches) != {"dsl", "baseline"} or any(len(v) != 4 for v in approaches.values()):
                raise ValueError("Expected four tasks per approach for " + pid)
            means = {a: sum(r[metric] for r in rows) / len(rows) for a, rows in approaches.items()}
            differences.append(means["baseline"] - means["dsl"])
        values.append(sum(differences) / 2)
    return values


def freeze(args):
    config = read(args.config)
    manifest = read(args.materials / "manifest.json")
    if config["mode"] not in {"pilot", "confirmatory"}:
        raise ValueError("Choose pilot or confirmatory mode")
    if not re.fullmatch(r"[0-9a-f]{64}", config.get("generator_class_sha256", "")):
        raise ValueError("Pin the actual generator class SHA-256 from an export receipt")
    if config["mode"] == "confirmatory":
        for key in ("independent_equivalence_reviewer", "review_record", "minimum_effect_rationale", "recruitment_justification"):
            if not config.get(key):
                raise ValueError("Complete before confirmatory execution: " + key)
        if not (0 < config.get("minimum_effect", 0) <= 1):
            raise ValueError("Specify the smallest useful normalised-time difference")
        if config["participants"] < 4 or config["participants"] % 4:
            raise ValueError("Recruitment must balance two tool orders and both variant sets")
        power = read(args.config.parent / config["power_report"])
        if power.get("delta") != config["minimum_effect"] or not power.get("candidate_participants"):
            raise ValueError("Power assumptions do not match the primary effect")
        if config["participants"] < power["candidate_participants"]:
            raise ValueError("Recruitment below the justified planning candidate")
        if not all(i.get("reviewed_by") for i in manifest["items"]):
            raise ValueError("Task expectations and baseline scope require documented review")
        if not (args.config.parent / config["review_record"]).is_file():
            raise ValueError("The documented review record file is missing")
    if config["task_limit_seconds"] <= 0 or config["participants"] % 4:
        raise ValueError("Positive task limit and participant count in multiples of four required")
    new_dir(args.out)
    save(args.out / "config.json", config)
    save(args.out / "manifest.json", manifest)
    lock = {"status": "FROZEN_PROTOCOL_NOT_RESULTS", "frozen_at_utc": stamp(),
            "materials": str(args.materials.resolve()),
            "materials_manifest": {n: h for n, h in tree(args.materials).items() if "/dsl-export/" not in "/" + n},
            "config_sha256": sha(args.out / "config.json"), "manifest_sha256": sha(args.out / "manifest.json"),
            "code": {name: sha(ROOT / "tools" / name) for name in
                     ("controlled_studies.py", "study_materials.py", "study_statistics.py")},
            "review_record": config.get("review_record")}
    if config.get("power_report"):
        shutil.copy2(args.config.parent / config["power_report"], args.out / "power.json")
        lock["power_sha256"] = sha(args.out / "power.json")
    if config.get("review_record"):
        shutil.copy2(args.config.parent / config["review_record"], args.out / "review.md")
        lock["review_sha256"] = sha(args.out / "review.md")
    save(args.out / "lock.json", lock)
    return {"status": lock["status"], "lock_sha256": sha(args.out / "lock.json")}


def locked(folder):
    lock = read(folder / "lock.json")
    config = read(folder / "config.json")
    if sha(folder / "config.json") != lock["config_sha256"] or sha(folder / "manifest.json") != lock["manifest_sha256"]:
        raise ValueError("Frozen protocol was modified")
    for name, expected in lock["code"].items():
        if sha(ROOT / "tools" / name) != expected:
            raise ValueError("Analysis/tool code differs from frozen version")
    if lock.get("power_sha256") and sha(folder / "power.json") != lock["power_sha256"]:
        raise ValueError("Power report was modified")
    if lock.get("review_sha256") and sha(folder / "review.md") != lock["review_sha256"]:
        raise ValueError("Independent review record was modified")
    return lock, config, read(folder / "manifest.json")


def study1(args):
    lock, config, manifest = locked(args.plan)
    materials = Path(lock["materials"])
    # Exports are new files. Verify the originally frozen maintained inputs only.
    for name, digest in lock["materials_manifest"].items():
        if sha(inside(materials, name)) != digest:
            raise ValueError("Maintained inputs changed since freezing: " + name)
    new_dir(args.out)
    rows = []
    for item in manifest["items"]:
        folder = inside(materials, item["directory"])
        phases = ("before", "after") if item["kind"] == "evolution" else ("",)
        observations = {}
        for phase in phases:
            current = folder / phase
            receipt = verify_export(current / "dsl-export", current / "model.mlops", config["generator_class_sha256"])
            output = args.out / item["id"] / (phase or "fault")
            status = build_baseline(current / "baseline", output, args.kubectl)
            result = {"dsl_receipt": receipt, "baseline_native_build": status}
            if item["expected_valid"]:
                if status == "BLOCKED":
                    result["baseline_correct"] = "BLOCKED"
                elif status != "PASS":
                    result["baseline_correct"] = False
                else:
                    result["baseline_observation"] = inspect(item["provider"], output / "artifacts", read(current / "contract.json"))
                    result["baseline_correct"] = passes(result["baseline_observation"])
                result["dsl_correct"] = False
                if receipt["generator"] == "ACCEPT":
                    result["dsl_observation"] = inspect(item["provider"], current / "dsl-export/artifacts", read(current / "contract.json"))
                    result["dsl_correct"] = not receipt["diagnostics"] and passes(result["dsl_observation"])
            else:
                target = item["expected_diagnostic"]
                diagnostics = receipt["diagnostics"]
                result["dsl_detected"] = receipt["generator"] == "REJECT" and any(target in x for x in diagnostics)
                result["dsl_unrelated_diagnostics"] = [x for x in diagnostics if target not in x]
                result["dsl_fault_outcome"] = "DETECTED" if result["dsl_detected"] and not result["dsl_unrelated_diagnostics"] else "UNATTRIBUTED_FAILURE" if diagnostics else "MISSED"
                result["baseline_guard"] = "BLOCKED"
                if status == "PASS":
                    from journal_common import parse, domain_checks
                    from run_gcp_comparison import gcp_domain_checks
                    docs, errors = parse(output / "artifacts")
                    issues = (domain_checks if item["provider"] == "azure" else gcp_domain_checks)(docs) if not errors else []
                    result["baseline_guard"] = "BLOCKED" if errors else "DETECTED" if any(x["rule"] == item["expected_rule"] for x in issues) else "MISSED"
                    if any(x["rule"] != item["expected_rule"] for x in issues):
                        result["baseline_guard"] = "UNATTRIBUTED_FAILURE"
                    result["baseline_issues"] = issues
                elif status == "FAIL":
                    # Attribute expected Kustomize port-source failures only.
                    error = (output / "stderr.txt").read_text()
                    result["baseline_guard"] = "DETECTED" if item["expected_rule"] == "S04" and "spec.ports.0.port" in error and "missing" in error.lower() else "UNATTRIBUTED_FAILURE"
            observations[phase or "fault"] = result
        if item["kind"] == "evolution":
            source_changes = {}
            # Restrict maintained counts to model.mlops or baseline, excluding exports/contracts.
            for approach, names in (("dsl", ["model.mlops"]), ("baseline", sorted(tree(folder / "before/baseline").keys() | tree(folder / "after/baseline").keys()))):
                first = folder / "before" / ("baseline" if approach == "baseline" else "")
                last = folder / "after" / ("baseline" if approach == "baseline" else "")
                source_changes[approach] = {"files_changed": sum(
                    (sha(first / n) if (first / n).exists() else None) !=
                    (sha(last / n) if (last / n).exists() else None) for n in names)}
            for approach in ("dsl", "baseline"):
                first = folder / "before/dsl-export/artifacts" if approach == "dsl" else args.out / item["id"] / "before/artifacts"
                last = folder / "after/dsl-export/artifacts" if approach == "dsl" else args.out / item["id"] / "after/artifacts"
                if observations["before"].get(approach + "_correct") is True and observations["after"].get(approach + "_correct") is True:
                    changes = unintended_changes(first, last, read(folder / "before/contract.json"), read(folder / "after/contract.json"))
                    observations["after"][approach + "_unintended_changes"] = changes
                    observations["after"][approach + "_correct"] = not changes
        else:
            source_changes = None
        rows.append({**item, "observations": observations, "source_changes": source_changes})
    save(args.out / "report.json", {"status": "EXECUTED_DEVELOPMENT_BENCHMARK" if all(x["development"] for x in rows) else "EXECUTED_BENCHMARK",
         "recorded_at_utc": stamp(), "plan_sha256": sha(args.plan / "lock.json"), "rows": rows,
         "independent_projects": sorted({x["project_id"] for x in rows if not x["development"]}),
         "inference": "DESCRIPTIVE_ONLY_UNTIL_INDEPENDENT_PROJECT_SAMPLING_IS_JUSTIFIED",
         "terraform_validate": "NOT_EXECUTED_BY_THIS_RUNNER", "cloud_apply": "NOT_EXECUTED"})
    return {"status": "OBSERVATIONS_SAVED", "tasks": len(rows), "report": str(args.out / "report.json")}


def allocate(args):
    lock, config, manifest = locked(args.plan)
    with args.roster.open(encoding="utf-8-sig", newline="") as f:
        people = list(csv.DictReader(f))
    if len(people) != config["participants"] or len({p["participant_id"] for p in people}) != len(people):
        raise ValueError("Unique roster must match frozen recruitment target")
    if any(not re.fullmatch(r"P\d{3,5}", p["participant_id"]) or not p.get("stratum") for p in people):
        raise ValueError("Use anonymous P001-style identifiers and predeclared experience strata")
    rng = random.Random(config["seed"])
    rows, block = [], 0
    for stratum in sorted({p["stratum"] for p in people}):
        group = [p["participant_id"] for p in people if p["stratum"] == stratum]
        if len(group) % 4:
            raise ValueError("Each stratum needs complete four-person sets to balance variants")
        rng.shuffle(group)
        for pair in range(0, len(group), 2):
            variant_first = "A" if pair % 4 == 0 else "B"
            block += 1
            members = group[pair:pair + 2]
            rng.shuffle(members)
            for i, pid in enumerate(members):
                first = "dsl" if i == 0 else "baseline"
                for period in (1, 2):
                    approach = first if period == 1 else ("baseline" if first == "dsl" else "dsl")
                    variant = variant_first if period == 1 else ("B" if variant_first == "A" else "A")
                    families = list(FAMILIES)
                    rng.shuffle(families)
                    for order, family in enumerate(families, 1):
                        item = next(x for x in manifest["items"] if x["provider"] == "azure" and x["family"] == family and x["variant"] == variant)
                        rows.append({"participant_id": pid, "block_id": f"B{block:03}", "stratum": stratum,
                                     "period": period, "slot": (period - 1) * 4 + order,
                                     "approach": approach, "task_id": item["id"], "family": family})
    new_dir(args.out)
    save(args.out / "allocation.json", {"plan": str(args.plan.resolve()), "plan_sha256": sha(args.plan / "lock.json"), "rows": rows})
    return {"status": "ALLOCATED_NOT_OBSERVED", "participants": len(people), "blocks": block, "tasks": len(rows)}


def start(args):
    allocation = read(args.allocation)
    plan = Path(allocation["plan"])
    lock, config, manifest = locked(plan)
    if allocation["plan_sha256"] != sha(plan / "lock.json"):
        raise ValueError("Allocation belongs to another protocol")
    row = next(x for x in allocation["rows"] if x["participant_id"] == args.participant and x["slot"] == args.slot)
    if args.session.name != f"{args.slot:02}" or args.session.parent.name != args.participant:
        raise ValueError("Use sessions/P001/01-style directories, matching participant and slot")
    for previous in range(1, args.slot):
        result = args.session.parent / f"{previous:02}" / "result.json"
        if not result.exists():
            raise ValueError("Complete earlier allocated slots before starting this task")
    item = next(x for x in manifest["items"] if x["id"] == row["task_id"])
    source = inside(Path(lock["materials"]), item["directory"]) / "before"
    new_dir(args.session)
    working = args.session / "working"
    working.mkdir()
    if row["approach"] == "dsl":
        receipt = verify_export(source / "dsl-export", source / "model.mlops", config["generator_class_sha256"])
        if receipt["generator"] != "ACCEPT" or receipt["diagnostics"]:
            raise ValueError("Starting DSL configuration is invalid")
        shutil.copy2(source / "model.mlops", working / "model.mlops")
        reference = source / "dsl-export/artifacts"
    else:
        shutil.copytree(source / "baseline", working / "baseline")
        if build_baseline(source / "baseline", args.session / "starting-build", args.kubectl) != "PASS":
            raise ValueError("Starting baseline build failed")
        reference = args.session / "starting-build/artifacts"
    if not passes(inspect(item["provider"], reference, read(source / "contract.json"))):
        raise ValueError("Starting configuration fails its frozen contract")
    save(args.session / "session.json", {**row, "plan": str(plan.resolve()), "plan_sha256": sha(plan / "lock.json"),
        "allocation_sha256": sha(args.allocation), "reference": str(reference.resolve()), "reference_manifest": tree(reference),
        "started_at_utc": stamp(), "started_monotonic": time.monotonic(),
        "limit_seconds": config["task_limit_seconds"], "instruction": item["instruction"], "state": "OPEN"})
    return {"instruction": item["instruction"], "workspace": str(working), "limit_seconds": config["task_limit_seconds"]}


def attempt(args):
    session = read(args.session / "session.json")
    if (args.session / "result.json").exists():
        raise ValueError("Session is already closed")
    lock, config, manifest = locked(Path(session["plan"]))
    item = next(x for x in manifest["items"] if x["id"] == session["task_id"])
    current = inside(Path(lock["materials"]), item["directory"])
    before, after = current / "before", current / "after"
    for phase in (before, after):
        name = (phase / "contract.json").relative_to(Path(lock["materials"])).as_posix()
        if sha(phase / "contract.json") != lock["materials_manifest"][name]:
            raise ValueError("Frozen scoring contract changed")
    n = max([int(p.name.split("-")[1]) for p in args.session.glob("attempt-*") if p.is_dir()] + [0]) + 1
    out = args.session / f"attempt-{n:03}"
    new_dir(out)
    blocked = False
    if session["approach"] == "dsl":
        if args.export is None:
            raise ValueError("Provide the actual Xtext --export folder")
        receipt = verify_export(args.export, args.session / "working/model.mlops", config["generator_class_sha256"])
        shutil.copytree(args.export, out / "export")
        shutil.copy2(args.session / "working/model.mlops", out / "source.mlops")
        accepted = receipt["generator"] == "ACCEPT" and not receipt["diagnostics"]
        root = out / "export/artifacts"
    else:
        shutil.copytree(args.session / "working/baseline", out / "source")
        status = build_baseline(out / "source", out / "build", args.kubectl)
        blocked, accepted = status == "BLOCKED", status == "PASS"
        root = out / "build/artifacts"
    observation = inspect(item["provider"], root, read(after / "contract.json")) if accepted else None
    unexpected = unintended_changes(Path(session["reference"]), root, read(before / "contract.json"), read(after / "contract.json")) if accepted else []
    correct = bool(accepted and passes(observation) and not unexpected)
    duration = time.monotonic() - session["started_monotonic"]
    if not 0 <= duration < 7 * 86400:
        raise ValueError("Monotonic timer invalid, possibly machine restart. Record infrastructure interruption.")
    save(out / "receipt.json", {"attempt": n, "elapsed_seconds": duration, "correct": correct,
        "blocked": blocked, "observation": observation, "unintended_changes": unexpected, "artifact_manifest": tree(root),
        "after_contract_sha256": sha(after / "contract.json"), "recorded_at_utc": stamp()})
    if correct or duration >= session["limit_seconds"]:
        return close_result(args.session, "correct" if correct and duration <= session["limit_seconds"] else "timeout", duration)
    return {"status": "ATTEMPT_RECORDED", "correct": False, "elapsed_seconds": duration, "blocked": blocked}


def close_result(folder, reason, duration):
    session = read(folder / "session.json")
    if (folder / "result.json").exists():
        raise ValueError("Session is already closed")
    excluded = reason in {"infrastructure", "withdrawn"}
    success = reason == "correct"
    score = min(duration / session["limit_seconds"], 1.) if success else 1.
    result = {**session, "reason": reason, "success": success, "elapsed_seconds": duration,
              "normalised_capped_time": score, "failure": int(not success), "excluded": excluded,
              "attempts": len(list(folder.glob("attempt-*/receipt.json"))), "closed_at_utc": stamp()}
    save(folder / "result.json", result)
    return {"status": "SESSION_CLOSED", "reason": reason, "success": success}


def analyse(args):
    allocation = read(args.allocation)
    plan = Path(allocation["plan"])
    _, config, _ = locked(plan)
    expected = {(r["participant_id"], r["slot"]): r for r in allocation["rows"]}
    actual = {}
    for path in args.sessions.rglob("result.json"):
        row = read(path)
        key = (row["participant_id"], row["slot"])
        if key not in expected or key in actual or row["plan_sha256"] != sha(plan / "lock.json"):
            raise ValueError("Duplicate/unassigned session or protocol mismatch")
        if any(row[k] != expected[key][k] for k in ("block_id", "approach", "task_id", "period", "family")):
            raise ValueError("Session differs from its random allocation")
        if row["allocation_sha256"] != sha(args.allocation):
            raise ValueError("Allocation changed since the session")
        if tree(Path(row["reference"])) != row["reference_manifest"]:
            raise ValueError("Starting-state reference has changed")
        # Recompute outcome from retained attempts. Hand-entered results cannot replace receipts.
        attempts = [read(p) for p in sorted(path.parent.glob("attempt-*/receipt.json"))]
        if not row["excluded"] and row["reason"] not in {"correct", "timeout", "abandoned"}:
            raise ValueError("Unknown non-excluded outcome")
        if row["excluded"] != (row["reason"] in {"infrastructure", "withdrawn"}):
            raise ValueError("Exclusion does not match the prespecified reasons")
        for receipt_path in sorted(path.parent.glob("attempt-*/receipt.json")):
            attempt_data = read(receipt_path)
            attempt_root = receipt_path.parent
            artifact_root = attempt_root / ("export/artifacts" if row["approach"] == "dsl" else "build/artifacts")
            if tree(artifact_root) != attempt_data["artifact_manifest"]:
                raise ValueError("Attempt artifacts changed after scoring")
            if row["approach"] == "dsl":
                verify_export(attempt_root / "export", attempt_root / "source.mlops", config["generator_class_sha256"])
            else:
                build = read(attempt_root / "build/receipt.json")
                if build["source"] != tree(attempt_root / "source"):
                    raise ValueError("Baseline source snapshot changed after scoring")
        successful = [a for a in attempts if a["correct"] and not a["blocked"] and a["elapsed_seconds"] <= row["limit_seconds"]]
        if row["success"] != bool(successful):
            raise ValueError("Success outcome contradicts attempt receipts")
        elapsed = min(a["elapsed_seconds"] for a in successful) if successful else row["limit_seconds"]
        row["normalised_capped_time"] = min(elapsed / row["limit_seconds"], 1.)
        row["failure"] = int(not bool(successful))
        actual[key] = row
    missing = sorted(set(expected) - set(actual))
    if missing:
        raise ValueError("Incomplete data. Missing assigned sessions: " + str(missing))
    excluded = {r["block_id"] for r in actual.values() if r["excluded"]}
    records = [r for r in actual.values() if r["block_id"] not in excluded]
    if len(records) < 32:
        raise ValueError("At least two complete four-person sets are required for this analysis")
    new_dir(args.out)
    result = {"status": "PILOT_ANALYSIS" if config["mode"] == "pilot" else "CONFIRMATORY_ANALYSIS",
              "plan_sha256": sha(plan / "lock.json"), "primary_outcome": "mean normalised capped time",
              "positive_difference_favours": "dsl", "excluded_blocks": sorted(excluded),
              "exclusion_reasons": [{k: r[k] for k in ("participant_id", "slot", "block_id", "reason")}
                                    for r in actual.values() if r["excluded"]]}
    result["primary"] = paired_summary(block_values(records, "normalised_capped_time"), config["seed"])
    # Secondary accuracy estimate is reported without another confirmatory p-value.
    result["secondary_failure_difference"] = paired_summary(block_values(records, "failure"), config["seed"])
    result["secondary_failure_difference"].pop("p_two_sided", None)
    result["recruitment_target_met_after_exclusions"] = len({r["participant_id"] for r in records}) == config["participants"]
    result["inferential_scope"] = "Conditional on these tasks, recruitment and no material carryover; not all MLOps projects"
    result["period_descriptives"] = {str(period): {a: {
        "mean_normalised_capped_time": sum(r["normalised_capped_time"] for r in records if r["period"] == period and r["approach"] == a) / sum(r["period"] == period and r["approach"] == a for r in records),
        "correct_tasks": sum(r["success"] for r in records if r["period"] == period and r["approach"] == a),
        "total_tasks": sum(r["period"] == period and r["approach"] == a for r in records)}
        for a in ("dsl", "baseline")} for period in (1, 2)}
    save(args.out / "report.json", result)
    save(args.out / "observations.json", list(actual.values()))
    from study_plots import participant_plot
    participant_plot(records, args.out / "participant-differences.png")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    p = sub.add_parser("prepare"); p.add_argument("--out", type=Path, required=True)
    p = sub.add_parser("power")
    p.add_argument("--delta", type=float, required=True); p.add_argument("--block-sd", type=float, required=True)
    p.add_argument("--out", type=Path, required=True); p.add_argument("--simulations", type=int, default=1000)
    p = sub.add_parser("freeze")
    p.add_argument("--config", type=Path, required=True); p.add_argument("--materials", type=Path, required=True); p.add_argument("--out", type=Path, required=True)
    p = sub.add_parser("study1")
    p.add_argument("--plan", type=Path, required=True); p.add_argument("--out", type=Path, required=True); p.add_argument("--kubectl", default="kubectl")
    p = sub.add_parser("allocate")
    p.add_argument("--plan", type=Path, required=True); p.add_argument("--roster", type=Path, required=True); p.add_argument("--out", type=Path, required=True)
    p = sub.add_parser("start")
    p.add_argument("--allocation", type=Path, required=True); p.add_argument("--participant", required=True)
    p.add_argument("--slot", type=int, required=True); p.add_argument("--session", type=Path, required=True)
    p.add_argument("--kubectl", default="kubectl")
    p = sub.add_parser("attempt")
    p.add_argument("--session", type=Path, required=True); p.add_argument("--export", type=Path); p.add_argument("--kubectl", default="kubectl")
    p = sub.add_parser("close")
    p.add_argument("--session", type=Path, required=True); p.add_argument("--reason", choices=["timeout", "abandoned", "infrastructure", "withdrawn"], required=True)
    p = sub.add_parser("analyse")
    p.add_argument("--allocation", type=Path, required=True); p.add_argument("--sessions", type=Path, required=True); p.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.action == "prepare": result = materialise(args.out)
        elif args.action == "power":
            if args.out.exists(): raise ValueError("Preserve previous power assumptions, choose a new file")
            result = plan_power(args.delta, args.block_sd, simulations=args.simulations); save(args.out, result)
        elif args.action == "close":
            session = read(args.session / "session.json")
            duration = time.monotonic() - session["started_monotonic"]
            if args.reason == "timeout" and duration < session["limit_seconds"]:
                raise ValueError("Time limit not reached. Use abandoned for a deliberate early stop")
            result = close_result(args.session, args.reason, duration)
        else: result = globals()[args.action](args)
        print(json.dumps(result, indent=2))
        return 0
    except (ValueError, OSError, KeyError, StopIteration) as exc:
        parser.error(str(exc))


