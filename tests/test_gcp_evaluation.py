"""Tooling QA only. Temporary fixtures are not observed DSL/GCP results."""
import hashlib
import json
import os
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import run_gcp_comparison as gcp
from journal_common import digest, parse
from run_journal_comparison import materialize


class GcpEvaluationTest(unittest.TestCase):
    def test_runtime_and_test_resources_match(self):
        test = ROOT / "org.xtext.ucd.mlopsdsl.tests/src/validation/gcp"
        self.assertEqual(gcp.FIXTURE.read_bytes(), (test / "c10_fraud_gcp.mlops").read_bytes())
        self.assertEqual((gcp.STUDY / "cases.tsv").read_bytes(), (test / "cases.tsv").read_bytes())
        rows = gcp.cases()
        self.assertEqual(len({c["case_id"] for c in rows}), 14)
        self.assertEqual(sum(c["category"] == "fault" for c in rows), 7)
        self.assertEqual(sum(c["category"] == "evolution" for c in rows), 3)

    def test_authored_baseline_meets_fixed_contract(self):
        result = gcp.inspect(gcp.STUDY / "baseline", gcp.contract_for(gcp.cases()[0]))
        self.assertEqual(gcp.failures(result), [])
        ids = [x["id"] for x in result["requirements"]]
        self.assertEqual(len(ids), len(set(ids)))

    def test_faults_are_distinct_from_finite_numeric_or_boolean_values(self):
        self.assertFalse(gcp.equal(True, 1))
        self.assertFalse(gcp.equal(float("nan"), float("nan")))
        self.assertTrue(gcp.equal(0.85, 0.8500000238418579))
        docs, errors = parse(gcp.STUDY / "baseline")
        self.assertFalse(errors)
        pool = next(v for b in docs["infra/terraform/main.tf"]["resource"]
                    for v in b.get("google_container_node_pool", {}).values())
        pool["initial_node_count"] = 1
        self.assertEqual({x["rule"] for x in gcp.gcp_domain_checks(docs)}, {"S07"})

    def test_mutations_have_explicit_source_targets_and_handle_crlf(self):
        text = gcp.FIXTURE.read_text(encoding="utf-8")
        for c in gcp.cases():
            result = gcp.changed_source(text, c)
            self.assertEqual(result, gcp.changed_source(text.replace("\n", "\r\n"), c))
            if c["old"]:
                self.assertNotEqual(result, text, c["case_id"])
        case = {"case_id": "bad", "old": "missing-marker", "new": "x"}
        with self.assertRaisesRegex(ValueError, "Missing mutation target"):
            gcp.changed_source(text, case)

    def synthetic_exports(self, root):
        """Minimal integrity-test fixture, never an experiment or generator substitute."""
        cases = []
        source = gcp.FIXTURE.read_bytes().decode("utf-8")
        for c in gcp.cases():
            case_root = root / c["case_id"]
            case_root.mkdir()
            text = gcp.changed_source(source, c)
            (case_root / "source.mlops").write_text(text, encoding="utf-8")
            fault = c["category"] == "fault"
            manifest = []
            if not fault:
                generated = case_root / "generated"
                generated.mkdir()
                f = generated / "qa-only.txt"
                f.write_text("Synthetic runner QA fixture. Not generated by the DSL.")
                manifest.append({"path": f.name, "sha256": digest(f)})
            cases.append({"case_id": c["case_id"], "category": c["category"],
                "outcome": "DETECTED" if fault else "PASS", "generator": "REJECT" if fault else "ACCEPT",
                "source_sha256": digest(case_root / "source.mlops"), "generated_manifest": manifest})
        data = {"base_sha256": digest(gcp.FIXTURE), "matrix_sha256": digest(gcp.STUDY / "cases.tsv"), "cases": cases}
        (root / "dsl-observations.json").write_text(json.dumps(data))
        return data

    def test_import_rejects_changed_outputs_and_duplicate_case_ids(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            data = self.synthetic_exports(root)
            gcp.import_observations(root)
            f = root / "GC00/generated/qa-only.txt"
            f.write_text("changed after export")
            with self.assertRaisesRegex(ValueError, "Generated manifest mismatch"):
                gcp.import_observations(root)
            data["cases"].append(data["cases"][0])
            (root / "dsl-observations.json").write_text(json.dumps(data))
            with self.assertRaisesRegex(ValueError, "duplicate GCP observation"):
                gcp.import_observations(root)

    def test_import_rejects_changed_case_matrix(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            data = self.synthetic_exports(root)
            data["matrix_sha256"] = "0" * 64
            (root / "dsl-observations.json").write_text(json.dumps(data))
            with self.assertRaisesRegex(ValueError, "different fixture or case matrix"):
                gcp.import_observations(root)

    def test_actual_kustomize_controls_and_fault_targets(self):
        kubectl = os.environ.get("MLOPS_TEST_KUBECTL") or shutil.which("kubectl")
        if not kubectl:
            self.skipTest("kubectl is needed for the actual Kustomize integration check")
        with tempfile.TemporaryDirectory() as d:
            for c in gcp.cases():
                root = Path(d) / c["case_id"]
                source = root / "source"
                shutil.copytree(gcp.STUDY / "baseline", source, ignore=shutil.ignore_patterns(".terraform"))
                gcp.mutate_baseline(source, c["case_id"])
                if c["case_id"] == "GF02":
                    with self.assertRaisesRegex(ValueError, "Kustomize build"):
                        materialize(root / "built", kubectl, root / "logs", source=source, runtime=source)
                    message = (root / "logs/kustomize.stderr.txt").read_text()
                    self.assertIn("spec.ports.0.port", message)
                    self.assertIn("missing", message.lower())
                    continue
                materialize(root / "built", kubectl, root / "logs", source=source, runtime=source)
                result = gcp.inspect(root / "built", gcp.contract_for(c))
                self.assertEqual(result["parsing_errors"], [], c["case_id"])
                if c["category"] == "fault":
                    self.assertEqual({x["rule"] for x in result["domain_oracle"]}, {c["rule"]}, c["case_id"])
                else:
                    self.assertEqual(gcp.failures(result), [], c["case_id"])


if __name__ == "__main__":
    unittest.main()
